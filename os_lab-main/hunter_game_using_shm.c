/**
 * ============================================================================
 * Ex 3 - Question 5: Hunter Game using System V Shared Memory
 * ============================================================================
 * Description:
 *   - Parent process generates a random target number between 1 and 100.
 *   - Creates a System V shared memory segment (shmget / shmat).
 *   - Forks two child processes (Child 1 and Child 2) acting as hunters.
 *   - Shared variables are declared outside the main() function.
 *   - Each child process repeatedly guesses random numbers between 1 and 100,
 *     waiting 1 second between guesses using sleep(1).
 *   - When a child guesses the target, it records its total guess count and
 *     sets the winner flag in shared memory.
 *   - Parent uses wait() to synchronize, reads results directly from shared
 *     memory, displays statistics, and cleans up the shared memory segment.
 *
 * Compilation:
 *   gcc -Wall -o hunter_game_using_shm hunter_game_using_shm.c
 *
 * Execution:
 *   ./hunter_game_using_shm
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>
#include <sys/ipc.h>
#include <sys/shm.h>
#include <time.h>

// Shared structure declared outside main() function as per lab rules
typedef struct {
    int target;             // Target number generated by parent
    int child1_guesses;     // Total guesses taken by Child 1
    int child2_guesses;     // Total guesses taken by Child 2
    int first_winner;       // 1 = Child 1 guessed first, 2 = Child 2 guessed first
} hunter_shared_t;

hunter_shared_t *shared;

int main() {
    // 1. Create System V Shared Memory segment
    int shmid = shmget(IPC_PRIVATE, sizeof(hunter_shared_t), IPC_CREAT | 0666);
    if (shmid < 0) {
        perror("shmget failed");
        exit(EXIT_FAILURE);
    }

    // 2. Attach shared memory segment
    shared = (hunter_shared_t *)shmat(shmid, NULL, 0);
    if (shared == (void *)-1) {
        perror("shmat failed");
        exit(EXIT_FAILURE);
    }

    // 3. Initialize shared game data
    srand(time(NULL));
    shared->target = (rand() % 100) + 1;
    shared->child1_guesses = 0;
    shared->child2_guesses = 0;
    shared->first_winner = 0;

    printf("====================================================\n");
    printf("   Hunter Game using System V Shared Memory (IPC)   \n");
    printf("====================================================\n");
    printf("[Parent PID %d] Target number generated: %d\n\n", getpid(), shared->target);

    // 4. Fork Child 1 (Hunter 1)
    pid_t c1 = fork();
    if (c1 < 0) {
        perror("Fork Child 1 failed");
        exit(EXIT_FAILURE);
    }

    if (c1 == 0) {
        // ---- Child 1 (Hunter 1) ----
        srand(time(NULL) ^ (getpid() << 16));
        int guesses = 0;
        int guess;

        printf("[Child 1 PID %d] Started hunting...\n", getpid());
        do {
            guess = (rand() % 100) + 1;
            guesses++;
            printf("[Child 1] Guess #%d: %d\n", guesses, guess);
            sleep(1);
        } while (guess != shared->target);

        shared->child1_guesses = guesses;
        if (shared->first_winner == 0) {
            shared->first_winner = 1;
        }

        printf(">>> [Child 1] MATCH FOUND! Target %d in %d guesses!\n", shared->target, guesses);
        shmdt(shared);
        exit(0);
    }

    // 5. Fork Child 2 (Hunter 2)
    pid_t c2 = fork();
    if (c2 < 0) {
        perror("Fork Child 2 failed");
        exit(EXIT_FAILURE);
    }

    if (c2 == 0) {
        // ---- Child 2 (Hunter 2) ----
        srand(time(NULL) ^ (getpid() << 8));
        int guesses = 0;
        int guess;

        printf("[Child 2 PID %d] Started hunting...\n", getpid());
        do {
            guess = (rand() % 100) + 1;
            guesses++;
            printf("[Child 2] Guess #%d: %d\n", guesses, guess);
            sleep(1);
        } while (guess != shared->target);

        shared->child2_guesses = guesses;
        if (shared->first_winner == 0) {
            shared->first_winner = 2;
        }

        printf(">>> [Child 2] MATCH FOUND! Target %d in %d guesses!\n", shared->target, guesses);
        shmdt(shared);
        exit(0);
    }

    // 6. Parent waits for both hunters to finish
    wait(NULL);
    wait(NULL);

    // 7. Display results from shared memory
    printf("\n================ GAME RESULTS ================\n");
    printf("Target Number           : %d\n", shared->target);
    printf("Child 1 Total Guesses   : %d\n", shared->child1_guesses);
    printf("Child 2 Total Guesses   : %d\n", shared->child2_guesses);
    printf("First to Reach Target   : Child %d\n", shared->first_winner);

    if (shared->child1_guesses < shared->child2_guesses) {
        printf("Winner by Fewest Guesses: Child 1 (%d vs %d)\n", shared->child1_guesses, shared->child2_guesses);
    } else if (shared->child2_guesses < shared->child1_guesses) {
        printf("Winner by Fewest Guesses: Child 2 (%d vs %d)\n", shared->child2_guesses, shared->child1_guesses);
    } else {
        printf("Winner by Fewest Guesses: Tie! Both took %d guesses.\n", shared->child1_guesses);
    }
    printf("==============================================\n");

    // 8. Cleanup shared memory
    shmdt(shared);
    shmctl(shmid, IPC_RMID, NULL);
    printf("[Parent] Shared memory segment successfully detached and removed.\n");

    return 0;
}

