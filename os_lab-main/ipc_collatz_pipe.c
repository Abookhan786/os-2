/**
 * ============================================================================
 * Problem: Collatz Conjecture (3n + 1) IPC Sequence Generator via UNIX Pipe
 * ============================================================================
 * Description:
 *   (Classic Operating System Concepts - Silberschatz Problem 3.21)
 *   Parent process takes a positive integer starting number N from user/argv.
 *   Child process calculates the Collatz sequence:
 *       - If n is even: n = n / 2
 *       - If n is odd : n = 3 * n + 1
 *   until n reaches 1.
 *   The child writes each generated number into a UNIX pipe.
 *   The parent process reads the numbers from the pipe and displays the sequence,
 *   as well as total step count.
 *
 * Compilation:
 *   gcc -Wall -o ipc_collatz_pipe ipc_collatz_pipe.c
 *
 * Execution:
 *   ./ipc_collatz_pipe 35
 *   or run without arguments for interactive prompt:
 *   ./ipc_collatz_pipe
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>

int main(int argc, char *argv[]) {
    long long n;

    // Read starting number from command-line argument or user input
    if (argc >= 2) {
        n = atoll(argv[1]);
    } else {
        printf("Enter a positive integer starting number (N): ");
        if (scanf("%lld", &n) != 1) {
            fprintf(stderr, "Invalid input.\n");
            return 1;
        }
    }

    if (n <= 0) {
        fprintf(stderr, "Error: Starting number must be a positive integer greater than 0.\n");
        return 1;
    }

    int pipe_fd[2];
    if (pipe(pipe_fd) == -1) {
        perror("pipe failed");
        return 1;
    }

    pid_t pid = fork();

    if (pid < 0) {
        perror("fork failed");
        return 1;
    }

    if (pid == 0) {
        // ==========================================
        // CHILD PROCESS (Sequence Generator)
        // ==========================================
        close(pipe_fd[0]); // Close read end

        long long current = n;
        // Write the initial starting number
        write(pipe_fd[1], &current, sizeof(long long));

        // Generate Collatz sequence until reaching 1
        while (current != 1) {
            if (current % 2 == 0) {
                current = current / 2;
            } else {
                current = 3 * current + 1;
            }
            write(pipe_fd[1], &current, sizeof(long long));
        }

        // Sentinel value (-1) to indicate end of stream
        long long end_flag = -1;
        write(pipe_fd[1], &end_flag, sizeof(long long));

        close(pipe_fd[1]);
        exit(0);
    } else {
        // ==========================================
        // PARENT PROCESS (Reader & Formatter)
        // ==========================================
        close(pipe_fd[1]); // Close write end

        printf("----------------------------------------------------------------\n");
        printf("Collatz (3n + 1) Sequence for N = %lld (generated by Child PID %d):\n", n, pid);
        printf("----------------------------------------------------------------\n");

        long long value;
        int step = 0;

        while (read(pipe_fd[0], &value, sizeof(long long)) > 0) {
            if (value == -1) break; // End of sequence
            if (step > 0) printf(" -> ");
            printf("%lld", value);
            step++;

            // Wrap lines for cleaner terminal formatting
            if (step % 10 == 0) printf("\n");
        }

        printf("\n----------------------------------------------------------------\n");
        printf("Total steps to reach 1: %d\n", step - 1);

        close(pipe_fd[0]);
        wait(NULL); // Wait for child to exit
    }

    return 0;
}
